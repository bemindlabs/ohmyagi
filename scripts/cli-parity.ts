/**
 * Differences this harness reports rather than hides.
 *
 * A declared difference is still printed, in full, on every run — the point of
 * the list is that each one costs a written reason, not that it disappears.
 *
 * ## Three kinds, and why there are three
 *
 * `number` was the only one, and it can express exactly one thing: *the same
 * line, with one captured number different*. That is enough for a file count
 * and nothing else. A change that **adds a line** to a command's output cannot
 * be declared by it at all — {@link compare} is positional, so one extra line
 * shifts every line after it and the run goes red on the shift rather than on
 * the change, with a length mismatch on top. The harness could therefore see
 * such a change but never be told about it, which leaves only two options for
 * whoever makes one: normalise it away (and lose every future change to the
 * same line, including one nobody meant) or stop running the harness.
 *
 * So:
 *
 * - `number` — the same line, one captured number different.
 * - `replaced` — a base line matching one pattern, a head line matching
 *   another, in the same position. For a line whose *text* changed on purpose.
 * - `inserted` — a head line matching a pattern that matches **nothing** on the
 *   base side of that case, removed before the positional compare and printed
 *   in full. The "nothing on base" condition is what keeps it narrow: a rule
 *   for a line that is new can never quietly swallow an edit to a line that
 *   already existed.
 * - `removed` — the mirror, for a line the head *stopped* printing, taken out
 *   of the **base** side before the compare. Its narrowness cannot come from
 *   `inserted`'s condition: fix3 deleted blank lines, and a blank line matches
 *   something on both sides of every case, so "matches nothing on the other
 *   side" would never be true and the kind would be unusable. `followedBy`
 *   replaces it — the rule names the lines that must come after the one it
 *   strips, so it fires at a *shape* rather than at a line.
 * - `crossed` — for output that changed **stream** and nothing else. It names
 *   one case and one step and no pattern at all, because the claim it makes is
 *   arithmetic rather than textual: *everything stdout lost at this step is
 *   everything stderr gained at this step, in order, byte for byte.* See
 *   {@link stripCrossings}.
 *
 * - `added` — for a **whole case** whose command the base revision does not
 *   have. It names the case and the command word and no pattern, because the
 *   claim it makes is not about any line: *every step of this case was refused
 *   by the base as an unknown command.* That is counted, not assumed — the
 *   number of `## step` markers on the base side has to equal the number of
 *   `unknown command "<word>"` lines on it — so the day the base learns the
 *   command the counts diverge, the rule stops firing, and the case is judged
 *   line by line like every other. It is the only kind that leaves a case
 *   uncompared, and the only honest answer when there is nothing to compare:
 *   a new command has no counterpart on the other side, and declaring its
 *   output line by line would be declaring the whole of it.
 *
 * ## Why `crossed` is not two rules, an `inserted` and a `removed`
 *
 * odd3 moved ~250 lines of `erase --json` from stdout to stderr. Declaring that
 * as a `removed` on stdout plus an `inserted` on stderr would have taken a
 * pattern broad enough to cover a whole certificate's worth of prose on each
 * side, and — worse — the two halves would never have been compared: a rule
 * pair like that reports parity when the block that arrived on stderr is
 * *different text* from the block that left stdout, which is exactly the
 * mistake this change could make and the one thing worth checking. `crossed`
 * cannot express "some text left and some other text arrived"; if the two
 * blocks differ by one byte it does not fire, and the case is red.
 *
 * ## Why `removed` is not a pair of `replaced` rules, which would have been easier
 *
 * A blank line that a command stopped printing could be declared as two
 * symmetric `replaced` rules — base blank → head text, base text → head blank.
 * {@link classify} judges one line at a time and cannot see order, so that pair
 * matches **in both directions**: the day somebody puts the deleted spacer
 * back, the pair declares it and the harness reports parity over a regression,
 * for good. `removed` only ever takes lines out of the base side, so the
 * opposite change — a head that gained the line — shifts everything after it
 * and goes red. `test/scripts/cli-parity.test.ts` runs that reverse direction
 * and asserts it is red, rather than describing it here and hoping.
 *
 * An insertion nobody declared still goes red, on the shift and on the length,
 * and `test/scripts/cli-parity.test.ts` has that control.
 */
export type Declared =
  | {
      readonly kind: "number";
      readonly id: string;
      readonly reason: string;
      readonly pattern: RegExp;
    }
  | {
      readonly kind: "replaced";
      readonly id: string;
      readonly reason: string;
      readonly base: RegExp;
      readonly head: RegExp;
    }
  | {
      readonly kind: "inserted";
      readonly id: string;
      readonly reason: string;
      readonly pattern: RegExp;
      /**
       * The last line of the insertion, for a block that spans several.
       *
       * Pretty-printed JSON gains whole objects, not lines: `"found": {` on its
       * own is unique and `},` on its own is not, so a per-line rule could
       * declare the opener and nothing else. With `until`, the rule names both
       * ends and everything between them goes as one insertion, printed whole.
       * A rule whose `until` never matches strips **nothing** — the anchor stays
       * where it is and the case goes red, which is the right answer for a
       * declaration that no longer describes the output.
       */
      readonly until?: RegExp;
    }
  | {
      readonly kind: "removed";
      readonly id: string;
      readonly reason: string;
      /** The base line to take out. */
      readonly pattern: RegExp;
      /**
       * The lines that must follow it, in order, for the rule to fire.
       *
       * Mandatory and never empty — it is the whole of this kind's narrowness.
       * `pattern` alone, for a rule about a blank line, would strip every blank
       * line in the recording; with the anchor, the rule describes a *shape*
       * that occurs where the change occurred and nowhere else, which is a
       * claim the run can be checked against rather than a wish.
       */
      readonly followedBy: readonly RegExp[];
    }
  | {
      readonly kind: "added";
      readonly id: string;
      readonly reason: string;
      /** The recording, by file name — `15-autonomy.txt`. */
      readonly file: string;
      /**
       * The command word the base revision does not have.
       *
       * Every step of the case has to begin with it. That is what makes the
       * rule's condition countable rather than a promise: see {@link addedCase}.
       */
      readonly command: string;
    }
  | {
      readonly kind: "crossed";
      readonly id: string;
      readonly reason: string;
      /** The recording, by file name — `13-erase.txt`. */
      readonly file: string;
      /**
       * The step within it, as `## step N` numbers them.
       *
       * Case and step rather than a pattern, and both are required: a rule that
       * could fire anywhere would be a licence to move output between streams
       * without saying where. Insert a step ahead of this one and the number is
       * wrong, the rule stops firing, and the case goes red — which is the
       * right answer for a declaration that has stopped describing the run.
       */
      readonly step: number;
    };

