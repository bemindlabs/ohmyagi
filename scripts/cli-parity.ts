/**
 * The string control 2 plants its one-character change inside.
 *
 * Exported because the control is only a control while the CLI still prints
 * this. If the message were reworded, control 2 would stop before it mutated
 * anything and say so — but only when somebody ran `--selftest`, which is by
 * hand. `test/scripts/cli-parity.test.ts` asserts the coupling on every run
 * instead, against `bin/` as it is today.
 */
export const CONTROL_NEEDLE = "ohmyagi: unknown command ";

/**
 * What control 3 plants: one line the base never printed.
 *
 * Control 2 changes a character, which the positional comparison catches on the
 * line itself. An *added* line is a different failure and the one the
 * `inserted` declarations are able to hide, so it gets a control of its own:
 * the extra line below matches no rule in {@link DECLARED}, and the run must go
 * red on it. Without this, growing the harness to declare fix1's new
 * certificate lines would have been a change to a proof tool with no proof.
 */
export const CONTROL_INSERTION = "ohmyagi: a line no declaration covers";

/**
 * Prove the harness is steady, then prove it is not blind.
 *
 * The first half runs the base twice and expects nothing. The second copies the
 * base, changes one character inside one error message, and expects red. Run
 * this before believing any "no difference" result — a comparison that cannot
 * fail is not evidence.
 */
async function selftest(baseSpec: string): Promise<number> {
  console.log("control 1 — the same revision twice must produce no difference");
  await runSide(baseSpec, "base");
  await runSide(baseSpec, "head");
  if ((await compare()) !== 0) {
    console.error("the harness is not steady: two runs of one revision disagreed.");
    return 1;
  }

  console.log("\ncontrol 2 — one changed character must be seen");
  const mutant = join(WORK, "mutant");
  await rm(mutant, { recursive: true, force: true });
  await mkdir(mutant, { recursive: true });
  await place(baseSpec);
  await run(["cp", "-a", `${ENGINE}/.`, mutant]);

  // One character, in a message every unknown command prints.
  const cli = join(mutant, "bin", "om-agi.ts");
  const source = await Bun.file(cli).text();
  if (!source.includes(CONTROL_NEEDLE)) {
    console.error(`control 2 cannot run: ${JSON.stringify(CONTROL_NEEDLE)} is not in the base CLI.`);
    return 1;
  }
  await writeFile(cli, source.replace(CONTROL_NEEDLE, "om-agi- unknown command "));

  await runSide(mutant, "head");
  if ((await compare()) === 0) {
    console.error("the harness is blind: it did not see a changed error message.");
    return 1;
  }
  console.log("\ncontrol 2 passed — the difference above is the planted one, and was caught.");

  console.log("\ncontrol 3 — one added line must be seen, declarations and all");
  await rm(mutant, { recursive: true, force: true });
  await mkdir(mutant, { recursive: true });
  await place(baseSpec);
  await run(["cp", "-a", `${ENGINE}/.`, mutant]);

  // A whole line rather than a character, printed where control 2 printed its
  // character. Nothing in DECLARED matches it, so the only honest answer is red
  // — and this is what keeps the `inserted` rules from being a way to make the
  // harness agree with whoever edits it.
  const added = await Bun.file(cli).text();
  if (!added.includes(CONTROL_NEEDLE)) {
    console.error(`control 3 cannot run: ${JSON.stringify(CONTROL_NEEDLE)} is not in the base CLI.`);
    return 1;
  }
  await writeFile(cli, added.replace(CONTROL_NEEDLE, `${CONTROL_INSERTION}\n${CONTROL_NEEDLE}`));

  await runSide(mutant, "head");
  if ((await compare()) === 0) {
    console.error("the harness is blind: it did not see a line that was added to the output.");
    return 1;
  }
  console.log("\ncontrol 3 passed — the added line above is the planted one, and was caught.");
  await rm(mutant, { recursive: true, force: true });

  console.log("\ncontrol 4 — a side with no engine in it must be refused, not compared");
  // The control for the third answer. Controls 1 to 3 all ask whether a
  // *difference* is seen; this one asks whether a comparison that never
  // happened is reported as one. Before this, two empty directories printed
  // PARITY-OK and exited 0 (odd2, D-P6), which is the one answer a proof tool
  // may not give for free.
  const hollow = join(WORK, "hollow");
  await rm(hollow, { recursive: true, force: true });
  await mkdir(hollow, { recursive: true });
  try {
    await runSide(hollow, "head");
    console.error("the harness ran a side with no engine in it instead of refusing.");
    return 1;
  } catch (error) {
    if (!(error instanceof ParityUndecided)) throw error;
    console.log(`control 4 passed — it refused: ${error.message}`);
  }
  await rm(hollow, { recursive: true, force: true });
  return 0;
}

