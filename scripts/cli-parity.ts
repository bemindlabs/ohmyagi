/** Everything under `dir`, as `path` plus normalised contents. */
async function record(dir: string, prefix = ""): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const lines: string[] = [];
  for (const entry of [...entries].sort((a, b) => a.name.localeCompare(b.name))) {
    if (UNRECORDED.has(entry.name)) continue;
    const rel = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      lines.push(`dir  ${rel}/`);
      lines.push(...(await record(path, rel)));
    } else if (entry.isSymbolicLink()) {
      lines.push(`link ${rel}`);
    } else {
      const bytes = await Bun.file(path).arrayBuffer();
      const text = new TextDecoder("utf8", { fatal: false }).decode(bytes);
      lines.push(`file ${rel}  (${bytes.byteLength} bytes before normalising)`);
      for (const line of text.split("\n")) lines.push(`  | ${line}`);
    }
  }
  return lines;
}

async function runScenario(scenario: Scenario): Promise<string> {
  const sandbox = join(RUNS, scenario.id);
  await rm(sandbox, { recursive: true, force: true });

  const home = join(sandbox, "home");
  const cwd = join(sandbox, "cwd");
  for (const dir of [home, cwd, join(sandbox, "state"), join(sandbox, "data"), join(sandbox, "config")]) {
    await mkdir(dir, { recursive: true });
  }

  // A PATH holding one symlink to bun and nothing else, plus an optional
  // directory of stub vendor CLIs. Never this machine's PATH: a real claude on
  // it would make half the matrix depend on somebody's login state.
  // `git` is on it because `new`, `rebuild`, `guard` and `erase` all really run
  // one — leaving it off would make four commands record an ENOENT stack trace
  // instead of their behaviour. It is not a vendor CLI and carries no identity.
  const bare = join(sandbox, "bare-bin");
  await mkdir(bare, { recursive: true });
  await symlink(tool("bun"), join(bare, "bun"));
  await symlink(tool("git"), join(bare, "git"));

  const stubs = join(sandbox, "stubs");
  await mkdir(stubs, { recursive: true });
  for (const name of ["claude", "codex"]) {
    const path = join(stubs, name);
    await writeFile(path, stubSource(name));
    await chmod(path, 0o755);
  }

  for (const [rel, contents] of scenario.files ?? []) {
    const path = join(cwd, rel);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, contents);
  }

  const lines: string[] = [`# ${scenario.id}`];
  const totals = new Map<string, number>();

  for (const [index, step] of scenario.steps.entries()) {
    const env: Record<string, string> = {
      HOME: home,
      PATH: step.path === "vendors" ? `${stubs}:${bare}` : bare,
      XDG_STATE_HOME: join(sandbox, "state"),
      XDG_DATA_HOME: join(sandbox, "data"),
      XDG_CONFIG_HOME: join(sandbox, "config"),
      XDG_CACHE_HOME: CACHE,
      CODEX_HOME: join(home, ".codex"),
      OLLAMA_HOST: DEAD,
      BUN_INSTALL_CACHE_DIR: CACHE,
      // git refuses to make a commit without these, and `new` runs `git init`.
      GIT_CONFIG_GLOBAL: "/dev/null",
      GIT_CONFIG_SYSTEM: "/dev/null",
      GIT_AUTHOR_NAME: "parity",
      GIT_AUTHOR_EMAIL: "parity@invalid",
      GIT_COMMITTER_NAME: "parity",
      GIT_COMMITTER_EMAIL: "parity@invalid",
    };

    const result = await run([...entryArgv(), ...step.argv], {
      cwd,
      env,
      ...(step.stdin === undefined ? {} : { stdin: step.stdin }),
    });

    const all = normalise(`${result.stdout}\u0000${result.stderr}`);
    for (const [name, hits] of all.counts) totals.set(name, (totals.get(name) ?? 0) + hits);
    const [stdout = "", stderr = ""] = all.text.split("\u0000");

    lines.push("");
    lines.push(`## step ${index} — om-agi ${step.argv.join(" ")}`);
    if (step.stdin !== undefined) lines.push(`stdin: ${JSON.stringify(step.stdin)}`);
    if (step.path === "vendors") lines.push("path: stub claude and codex on PATH");
    lines.push(`exit: ${result.code}`);
    lines.push("stdout:");
    for (const line of stdout.split("\n")) lines.push(`  | ${line}`);
    lines.push("stderr:");
    for (const line of stderr.split("\n")) lines.push(`  | ${line}`);
  }

  lines.push("");
  lines.push("## sandbox");
  lines.push(...(await record(sandbox)).map((line) => normalise(line).text));

  lines.push("");
  lines.push("## normaliser hits (must match, side for side)");
  for (const { name } of NORMALISERS) lines.push(`  ${name}: ${totals.get(name) ?? 0}`);

  return lines.join("\n") + "\n";
}

/** How the matrix, and the preflight below it, start the engine under test. */
function entryArgv(): readonly string[] {
  return BINARY ? [COMPILED] : [tool("bun"), "run", join(ENGINE, "bin", "om-agi.ts")];
}

/**
 * Every byte of the tree a side is about to run, as one hex digest.
 *
 * Taken straight after {@link place} and before anything has been run, so it is
 * a fact about the spec rather than about what the matrix left behind. Its only
 * use is the refusal in {@link main}: two *different* specs that resolve to the
 * same bytes have nothing between them to judge.
 */
export async function treeDigest(dir: string, hasher = new Bun.CryptoHasher("sha256")): Promise<string> {
  const walkInto = async (at: string, prefix: string): Promise<void> => {
    const entries = await readdir(at, { withFileTypes: true });
    for (const entry of [...entries].sort((a, b) => a.name.localeCompare(b.name))) {
      const rel = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
      const path = join(at, entry.name);
      if (entry.isDirectory()) {
        hasher.update(`dir ${rel}\n`);
        await walkInto(path, rel);
      } else if (entry.isSymbolicLink()) {
        hasher.update(`link ${rel}\n`);
      } else {
        hasher.update(`file ${rel}\n`);
        hasher.update(await Bun.file(path).arrayBuffer());
      }
    }
  };
  await walkInto(dir, "");
  return hasher.digest("hex");
}

/**
 * Is there an engine here, and does it run?
 *
 * Two questions, and the second is the one that closes the hole. A side with no
 * `bin/om-agi.ts` fails every invocation identically to the other side that has
 * none, which this harness would call parity; so would two sides whose engine
 * *is* there and cannot be imported. Only the exit code of `version` is read —
 * never its text — because comparing the text to something written down here
 * would be the golden file this file's header refuses to have.
 */
async function preflight(spec: string, side: string): Promise<void> {
  const source = join(ENGINE, "bin", "om-agi.ts");
  if (!(await Bun.file(source).exists())) {
    undecided(
      `the ${side} side (${spec}) has no bin/om-agi.ts in it. There is no engine here to ` +
        `compare, and two sides that both fail to start are not two sides that agree.`,
    );
  }

  // A home inside the workspace, so even a command that reads one cannot reach
  // the operator's. `version` needs none; it is given one anyway.
  const home = join(WORK, "preflight-home");
  await mkdir(home, { recursive: true });
  const alive = await run([...entryArgv(), "version"], {
    cwd: home,
    env: { HOME: home, PATH: `${dirname(tool("bun"))}:${dirname(tool("git"))}` },
  });
  if (alive.code !== 0) {
    undecided(
      `the ${side} side (${spec}) has a bin/om-agi.ts that does not run: \`ohmyagi version\` ` +
        `exited ${alive.code}. Every case would fail on this side, and a side that fails the ` +
        `same way as the other is not evidence that the two agree.`,
    );
  }
}

async function runSide(spec: string, side: string): Promise<string> {
  await place(spec);
  const digest = await treeDigest(ENGINE);
  if (BINARY) {
    await rm(COMPILED, { force: true });
    const built = await run([tool("bun"), "build", "bin/om-agi.ts", "--compile", "--outfile", COMPILED], {
      cwd: ENGINE,
    });
    if (built.code !== 0) throw new Error(`bun build failed for ${spec}: ${built.stderr}`);
    process.stderr.write(`  ${side}: compiled ${(await stat(COMPILED)).size} bytes\n`);
  }
  await preflight(spec, side);
  const dir = join(OUT, side);
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
  await rm(RUNS, { recursive: true, force: true });

  for (const scenario of selected()) {
    process.stderr.write(`  ${side}: ${scenario.id}\n`);
    await writeFile(join(dir, `${scenario.id}.txt`), await runScenario(scenario));
  }
  return digest;
}

