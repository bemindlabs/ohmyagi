/**
 * The scenarios this run covers — all of them, or the one `--only` names.
 *
 * Throws on a name that matches nothing. Returning `[]` would let every caller
 * below carry on happily: `runSide` would write no recordings, `compare` would
 * find no differences, and the run would print `PARITY-OK — 0 case(s)` and exit
 * 0. A typo in a flag must not be able to manufacture a proof.
 */
export function chosen(only: string | undefined): readonly Scenario[] {
  if (only === undefined) return SCENARIOS;
  const picked = SCENARIOS.filter((scenario) => scenario.id === only);
  if (picked.length === 0) {
    throw new Error(
      `--only ${only} names no scenario. Known ids: ${SCENARIOS.map((s) => s.id).join(", ")}`,
    );
  }
  return picked;
}

const selected = (): readonly Scenario[] => chosen(ONLY);

// ---------------------------------------------------------------------------
// Materialising a revision
// ---------------------------------------------------------------------------

async function run(
  argv: readonly string[],
  options: { cwd?: string; env?: Record<string, string>; stdin?: string } = {},
): Promise<{ code: number; stdout: string; stderr: string }> {
  const child = Bun.spawn(argv as string[], {
    ...(options.cwd === undefined ? {} : { cwd: options.cwd }),
    ...(options.env === undefined ? {} : { env: options.env }),
    stdin: options.stdin === undefined ? "ignore" : new TextEncoder().encode(options.stdin),
    stdout: "pipe",
    stderr: "pipe",
  });
  const stdout = await new Response(child.stdout).text();
  const stderr = await new Response(child.stderr).text();
  await child.exited;
  return { code: child.exitCode ?? -1, stdout, stderr };
}

/** True when `spec` names a commit in this repository rather than a directory. */
async function isRevision(spec: string): Promise<boolean> {
  if (spec.includes("/") || spec === "." || spec === "..") return false;
  return (await run(["git", "-C", REPO, "rev-parse", "--verify", `${spec}^{commit}`])).code === 0;
}

/**
 * One commit, unpacked at `into`.
 *
 * Through a file rather than a pipe: a tar read as text and written back is a
 * corrupt tar, and the failure would look like a difference in the engine.
 */
async function materialiseRevision(spec: string, into: string): Promise<void> {
  const tarball = join(WORK, "base.tar");
  const archive = Bun.spawn(["git", "-C", REPO, "archive", "--format=tar", "-o", tarball, spec], {
    stdout: "pipe",
    stderr: "pipe",
  });
  await archive.exited;
  if (archive.exitCode !== 0) {
    throw new Error(`git archive ${spec} failed: ${await new Response(archive.stderr).text()}`);
  }
  const extract = await run(["tar", "-x", "-f", tarball, "-C", into]);
  if (extract.code !== 0) throw new Error(`tar failed: ${extract.stderr}`);
  await rm(tarball, { force: true });
}

/** Copy the files git would track out of a working tree. */
async function copyTree(dir: string, into: string): Promise<void> {
  const listed = await run(["git", "-C", dir, "ls-files", "--cached", "--others", "--exclude-standard"]);
  const paths =
    listed.code === 0
      ? listed.stdout.split("\n").filter((line) => line !== "")
      : await walk(dir, dir);

  for (const rel of paths) {
    const from = join(dir, rel);
    const to = join(into, rel);
    let info;
    try {
      info = await stat(from);
    } catch {
      continue; // Deleted but still listed — nothing to copy.
    }
    if (!info.isFile()) continue;
    await mkdir(dirname(to), { recursive: true });
    await Bun.write(to, Bun.file(from));
    await chmod(to, info.mode & 0o777);
  }
}

/** Every file under `dir`, for a tree git does not know about. */
async function walk(root: string, dir: string): Promise<string[]> {
  const found: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name === ".git" || entry.name === "node_modules") continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await walk(root, path)));
    else if (entry.isFile()) found.push(relative(root, path));
  }
  return found;
}

/**
 * Put whichever kind of spec this is at `into`, and **nothing else with it**.
 *
 * The clearing is the load-bearing line. `copyTree` only ever writes files, so
 * without it the previous side's tree shows through wherever this side deleted
 * something: run `--base <rev> --head .` after deleting a file and the head
 * engine still has it, because the base unpacked it there a moment earlier.
 *
 * Measured, not imagined — it is how this was found. `--base HEAD --head .`
 * over a working tree with one file deleted from `scripts/` reported
 * `PARITY-OK` with not even a declared difference, because `doctor` counted 87
 * files on both sides. The harness could not see a deletion at all, which is
 * the one answer a proof tool may never give for free. `materialiseRevision`
 * used to clear for itself, so the revision path was right and the directory
 * path was wrong; clearing here means neither can drift from the other.
 */
export async function place(spec: string, into: string = ENGINE): Promise<void> {
  await rm(into, { recursive: true, force: true });
  await mkdir(into, { recursive: true });
  if (await isRevision(spec)) await materialiseRevision(spec, into);
  else await copyTree(spec, into);
}

