// main
// ---------------------------------------------------------------------------

const USAGE =
  "usage: bun run scripts/cli-parity.ts --base <rev|dir> (--head <rev|dir> | --selftest)" +
  " [--structure] [--binary] [--only <id>] [--work <dir>]";

async function judge(): Promise<number> {
  const baseSpec = flag("base");
  if (baseSpec === undefined) {
    console.error(USAGE);
    return 2;
  }

  await mkdir(CACHE, { recursive: true });

  if (Bun.argv.includes("--selftest")) return await selftest(baseSpec);

  const headSpec = flag("head");
  if (headSpec === undefined) {
    console.error(USAGE);
    return 2;
  }

  let code = 0;
  if (!Bun.argv.includes("--structure-only")) {
    const base = await runSide(baseSpec, "base");
    const head = await runSide(headSpec, "head");
    // Here rather than inside `compare`, and only when the two specs are
    // different words: `--selftest`'s control 1 runs one spec against itself on
    // purpose, and refusing that would take the harness's own steadiness check
    // with it. Two *different* names for one tree is the suspicious state —
    // `--base HEAD --head .` on a clean checkout is how it is usually typed.
    if (baseSpec !== headSpec && base === head) {
      undecided(
        `--base ${baseSpec} and --head ${headSpec} are two names for the same bytes ` +
          `(sha256 ${base.slice(0, 12)}…). There is no change here to judge, so an OK from this ` +
          `run would be an OK about nothing. Did the working tree get committed, or a revision ` +
          `get named twice?`,
      );
    }
    code = await compare();
  }
  if (Bun.argv.includes("--structure") || Bun.argv.includes("--structure-only")) {
    code = (await structure(baseSpec, headSpec)) || code;
  }
  return code;
}

/**
 * The three answers, and the one that is not a verdict.
 *
 * 0 and 1 are statements about two engines. 3 is a statement about this run:
 * it refused to judge. 2 stays what it was — a usage error. They are kept apart
 * so that a script reading the exit code cannot mistake "nothing to compare"
 * for "nothing differs", which is the whole reason the third answer exists.
 */
async function main(): Promise<number> {
  try {
    return await judge();
  } catch (error) {
    if (!(error instanceof ParityUndecided)) throw error;
    console.error(`\nPARITY-UNDECIDED — ${error.message}`);
    console.error(
      "Exit 3: this run refused to answer. That is not the same as finding no difference, and " +
        "nothing here says the two sides agree.",
    );
    return 3;
  }
}

// Behind `import.meta.main` so a test can import the matrix and the judging
// above without this file reading the test runner's command line, failing to
// find `--base`, and taking the whole suite down with `process.exit(2)`.
if (import.meta.main) process.exit(await main());
