/** Every `.ts` file under a directory, relative to it. */
async function tsFiles(dir: string, prefix = ""): Promise<string[]> {
  const found: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) found.push(...(await tsFiles(join(dir, entry.name), rel)));
    else if (entry.name.endsWith(".ts")) found.push(rel);
  }
  return found.sort();
}

/**
 * The two structural proofs, run over `bin/**` on both sides.
 *
 * *moved-lines*: the multiset of lines must be equal once the three permitted
 * edits are undone — an `import` line, the word `export ` in front of a
 * declaration, and one extra `../` on a relative specifier. This reaches the
 * branches a piped run cannot: `dim()` and `bold()` only emit escape codes on a
 * terminal, so no amount of running proves their bodies survived the move.
 *
 * *import-union*: the set of `(module, binding)` pairs imported from `src/`
 * must be equal. `noUnusedLocals` already forces each file to import only what
 * it uses, so equality here means the same code is reaching the same places.
 */
/**
 * A line of comment rather than a line of code.
 *
 * `*` must be followed by a space or nothing, so the one line of the help text
 * that begins `**drift**` is counted as what it is: prose inside a template
 * literal, and part of the program's output.
 */
export function isComment(line: string): boolean {
  const trimmed = line.trim();
  return (
    trimmed.startsWith("//") ||
    trimmed.startsWith("/*") ||
    trimmed.startsWith("*/") ||
    trimmed === "*" ||
    trimmed.startsWith("* ")
  );
}

async function structure(baseSpec: string, headSpec: string): Promise<number> {
  const read = async (
    spec: string,
  ): Promise<{ lines: string[]; comments: string[]; imports: Set<string> }> => {
    await place(spec);
    const lines: string[] = [];
    const comments: string[] = [];
    const imports = new Set<string>();
    for (const rel of await tsFiles(join(ENGINE, "bin"))) {
      const source = await Bun.file(join(ENGINE, "bin", rel)).text();
      const withoutImports = source.replace(/^import[\s\S]*?from\s+"[^"]+";$/gm, "");
      for (const line of withoutImports.split("\n")) {
        const stripped = line.replace(/^export /, "");
        if (stripped.trim() === "") continue;
        if (isComment(stripped)) comments.push(stripped);
        else lines.push(stripped);
      }
      for (const match of source.matchAll(/import\s+([\s\S]*?)\s+from\s+"([^"]+)";/g)) {
        const module = match[2]!.replace(/^(\.\.\/)+/, "");
        if (!module.startsWith("src/")) continue;
        for (const binding of match[1]!.replace(/[{}]/g, "").split(",")) {
          const name = binding.replace(/\btype\b/, "").trim();
          if (name !== "") imports.add(`${module}:${name}`);
        }
      }
    }
    return { lines: lines.sort(), comments: comments.sort(), imports };
  };

  const base = await read(baseSpec);
  const head = await read(headSpec);

  const problems: string[] = [];

  const onlyBase = difference(base.lines, head.lines);
  const onlyHead = difference(head.lines, base.lines);
  if (onlyBase.length > 0 || onlyHead.length > 0) {
    problems.push(`moved-lines: ${onlyBase.length} line(s) only on base, ${onlyHead.length} only on head`);
    for (const line of onlyBase.slice(0, 40)) problems.push(`  -${line}`);
    for (const line of onlyHead.slice(0, 40)) problems.push(`  +${line}`);
  }

  // Comments are reported, never gated: a file that moved gets a header saying
  // what it is for, and a header is the one thing a move is entitled to add.
  // Printed in full so that "only comments changed" is a claim a reader can
  // check rather than take.
  const commentBase = difference(base.comments, head.comments);
  const commentHead = difference(head.comments, base.comments);
  console.log(
    `\ncomment lines: ${commentBase.length} only on base, ${commentHead.length} only on head ` +
      `(reported, not gated — code lines are the gate above)`,
  );
  for (const line of commentBase) console.log(`  -${line.trim()}`);
  for (const line of commentHead) console.log(`  +${line.trim()}`);

  const missing = [...base.imports].filter((x) => !head.imports.has(x)).sort();
  const extra = [...head.imports].filter((x) => !base.imports.has(x)).sort();
  if (missing.length > 0 || extra.length > 0) {
    problems.push(`import-union: ${missing.length} missing, ${extra.length} extra`);
    for (const x of missing) problems.push(`  -${x}`);
    for (const x of extra) problems.push(`  +${x}`);
  }

  if (problems.length === 0) {
    console.log(
      `\nSTRUCTURE-OK — ${base.lines.length} line(s) of code under bin/ on each side, same multiset; ` +
        `${base.imports.size} (module, binding) pair(s) from src/, same set.`,
    );
    return 0;
  }
  for (const line of problems) console.error(line);
  return 1;
}

/** Multiset difference: what `a` has that `b` does not, counting repeats. */
export function difference(a: readonly string[], b: readonly string[]): string[] {
  return unmatched(a, b).map((at) => a[at]!);
}

