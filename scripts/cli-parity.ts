const REPO = join(import.meta.dir, "..");

/** `--name value` as it was written on the command line, or `undefined`. */
function flag(name: string): string | undefined {
  const at = Bun.argv.indexOf(`--${name}`);
  return at === -1 ? undefined : Bun.argv[at + 1];
}

/**
 * Where a given checkout keeps everything this harness writes.
 *
 * Keyed by the checkout, not a fixed string. It was `/tmp/om-agi-parity` flat,
 * and this repository is worked on in worktrees: two of them running the
 * harness at once shared one {@link ENGINE} and one {@link OUT}, so each side's
 * `base` was overwritten by the other's while the comparison read on. That
 * produces a *wrong proof*, quietly, which is the single outcome a tool whose
 * whole job is proof may not have — it does not fail, it agrees with you.
 *
 * A hash of the path rather than the path itself: `/tmp` is world-readable, and
 * a directory name there is a sentence about somebody's filesystem (D-021). The
 * hash is only for separation, so a weak one is the right one.
 */
export function workspaceFor(repo: string): string {
  return `/tmp/om-agi-parity-${Bun.hash(repo).toString(16)}`;
}

/**
 * Everything this harness writes, and nothing outside it. Never a home directory.
 *
 * `--work <dir>` overrides the per-checkout default.
 * `test/scripts/cli-parity.test.ts` passes a fresh `mkdtemp`, so the mini-run
 * inside `bun test` cannot disturb a full run somebody started by hand in the
 * same checkout — and cannot inherit its cached engine either, which would make
 * the mini-run's result depend on what happened before it.
 */
const WORK = flag("work") ?? workspaceFor(REPO);
/** Both revisions are unpacked here, one at a time, so `ENGINE_ROOT` is one string. */
const ENGINE = join(WORK, "engine");
/** Case sandboxes. The case id is in the path; the side is not. */
const RUNS = join(WORK, "runs");
/** Recordings, one directory per side. */
const OUT = join(WORK, "out");
/** Shared caches, kept out of every recorded tree. */
const CACHE = join(WORK, "cache");
/** Where `--binary` puts the compiled engine, one side at a time. */
const COMPILED = join(WORK, "om-agi");

/**
 * Run the matrix against `bun build --compile` output rather than the source.
 *
 * Worth a mode of its own because the compiled binary is the only place
 * `import.meta.dir` can answer differently after a split: in a checkout it is
 * the directory of the file it appears in, and in a single-file executable it
 * is whatever bun's virtual filesystem calls that module's directory. The two
 * sides are compared to each other, not to the source-mode run — a compiled
 * engine has no repository around it and is expected to say so.
 */
const BINARY = Bun.argv.includes("--binary");

/**
 * Run one scenario of the matrix instead of all fourteen, by id.
 *
 * For the mini-run in `bun test`: the full `--selftest` is 381 invocations and
 * ~16 seconds, which is the right price to pay by hand and the wrong one to add
 * to every test run. One scenario keeps *both controls* running automatically —
 * the half of this harness that would otherwise never be exercised except when
 * somebody remembered to.
 *
 * A value that names no scenario is refused rather than run: an empty matrix
 * compares nothing and would print `PARITY-OK — 0 case(s)`, which is a proof
 * tool reporting success for having done no work.
 */
const ONLY = flag("only");

/** A port nothing answers on, so "the daemon is down" is a fact and not a wait. */
const DEAD = "http://127.0.0.1:1";

/**
 * The two tools every invocation of this harness stands on, found or not found.
 *
 * Deliberately nullable. These were `Bun.which("bun") ?? "bun"`, and the
 * fallback is the exact shape this file now refuses: on a machine where bun is
 * not on PATH, both sides symlink a name that resolves to nothing, every
 * invocation on both sides fails with the same ENOENT, and the harness reports
 * parity over two engines that never ran. A missing tool is a reason not to
 * answer, so it is {@link undecided} rather than a default.
 *
 * Read once at startup, which is what `Bun.which` does — it reads the PATH this
 * process began with, not the PATH any child is handed.
 */
const BUN = Bun.which("bun");
const GIT = Bun.which("git");

/** The comparison did not happen. Not a difference, and not the absence of one. */
export class ParityUndecided extends Error {
  constructor(reason: string) {
    super(reason);
    this.name = "ParityUndecided";
  }
}

/** Refuse to judge, from wherever the reason was found. */
function undecided(reason: string): never {
  throw new ParityUndecided(reason);
}

/** Where `bun` or `git` is on this machine, or a refusal to run without it. */
function tool(name: "bun" | "git"): string {
  const found = name === "bun" ? BUN : GIT;
  if (found === null) {
    undecided(
      `${name} is not on this PATH. Both sides of this comparison run it, so both would fail ` +
        `identically — which this harness would otherwise report as parity.`,
    );
  }
  return found;
}

