export interface Difference {
  readonly file: string;
  readonly line: number;
  readonly base: string;
  readonly head: string;
}

/** One head-only line a rule allowed, kept so it can be printed in full. */
export interface Insertion {
  readonly file: string;
  readonly text: string;
  readonly by: Declared;
}

/** One base-only line a rule allowed, kept so it can be printed in full. */
export interface Removal {
  readonly file: string;
  readonly text: string;
  readonly by: Declared;
}

/** One block that changed stream, kept whole so it can be printed whole. */
export interface Crossing {
  readonly file: string;
  /** What left stdout, which is also — checked — what arrived on stderr. */
  readonly text: string;
  readonly by: Declared;
}

/** One step's two streams, as index ranges into the recording's lines. */
export interface StepStreams {
  /** `[from, to)` over the `  | ` lines under `stdout:`. */
  readonly stdout: readonly [number, number];
  /** `[from, to)` over the `  | ` lines under `stderr:`. */
  readonly stderr: readonly [number, number];
}

/**
 * Where each step's stdout and stderr live in a recording, by line index.
 *
 * The recording is written by {@link runScenario} and its shape is fixed there:
 * `## step N — om-agi …`, an `exit:` line, `stdout:`, its `  | ` lines,
 * `stderr:`, its `  | ` lines, and then a blank line and the next `## `. This
 * reads that back. A step whose two markers are not both present is skipped
 * rather than guessed at — the trailing `## sandbox` and `## normaliser hits`
 * sections have neither, and a malformed step must not silently become a
 * region that swallows the rest of the file.
 */
export function stepStreams(lines: readonly string[]): Map<number, StepStreams> {
  const found = new Map<number, StepStreams>();
  let step: number | undefined;
  let outFrom: number | undefined;
  let outTo: number | undefined;
  let errFrom: number | undefined;

  const close = (end: number): void => {
    if (step !== undefined && outFrom !== undefined && outTo !== undefined && errFrom !== undefined) {
      found.set(step, { stdout: [outFrom, outTo], stderr: [errFrom, end] });
    }
    step = outFrom = outTo = errFrom = undefined;
  };

  for (const [index, line] of lines.entries()) {
    if (line.startsWith("## ")) {
      close(index);
      const header = /^## step (\d+) /.exec(line);
      if (header !== null) step = Number(header[1]);
      continue;
    }
    if (step === undefined) continue;
    if (line === "stdout:") outFrom = index + 1;
    else if (line === "stderr:") {
      outTo = index;
      errFrom = index + 1;
    }
  }
  close(lines.length);
  return found;
}

/**
 * The indices of `a` that `b` has no copy of, as a multiset.
 *
 * The positional half of {@link difference}, which is written in terms of it so
 * that there is one implementation of "what does this side have that the other
 * does not" rather than two that can drift.
 */
function unmatched(a: readonly string[], b: readonly string[]): number[] {
  const counts = new Map<string, number>();
  for (const line of b) counts.set(line, (counts.get(line) ?? 0) + 1);
  const out: number[] = [];
  for (const [index, line] of a.entries()) {
    const left = counts.get(line) ?? 0;
    if (left > 0) counts.set(line, left - 1);
    else out.push(index);
  }
  return out;
}

/** The two sides of one crossing, by line index into each stream's region. */
interface Crossed {
  /** Positions in the base side's stdout that the head side no longer prints. */
  readonly fromStdout: readonly number[];
  /** Positions in the head side's stderr that the base side did not print. */
  readonly ontoStderr: readonly number[];
}

/**
 * The state space this search refuses to enter. See {@link crossing}.
 *
 * Five million is far past anything the matrix produces — the one real case is
 * about 90,000 — and small enough that a rule accidentally pointed at a step
 * with a long stderr on both sides fails fast instead of hanging a proof tool.
 */
const SEARCH_LIMIT = 5_000_000;

/**
 * Find the block that moved from stdout to stderr, if one did and nothing else
 * happened.
 *
 * The question is exact: **is `baseOut` an interleaving of `headOut` and some
 * sequence X, while `headErr` is an interleaving of `baseErr` and that same
 * X?** If it is, X is what left stdout, X is what arrived on stderr, and the
 * two are the same bytes in the same order by construction rather than by a
 * comparison somebody could get wrong.
 *
 * Posing it that way settles three things at once, which is why it is posed
 * that way rather than as two diffs:
 *
 * - `headOut` must be a *subsequence* of `baseOut`, so stdout gained nothing
 *   and nothing on it was reordered;
 * - `baseErr` must be a subsequence of `headErr`, so stderr lost nothing;
 * - and X is one sequence, so "some text left and some other text arrived"
 *   cannot be described at all.
 *
 * A diff-based version of this was written first and thrown away: with a
 * multiset difference, *which* of four identical blank lines is called "moved"
 * is arbitrary, and the answer to "did the same bytes arrive?" came out
 * different depending on which arbitrary choice each side made. This search has
 * no such choice to make — it asks whether a consistent assignment exists at
 * all.
 *
 * Walking it: at each step either a base stdout line stays on stdout (it
 * matches the next `headOut` line), or a head stderr line was already on base's
 * stderr, or one line crosses — which requires `baseOut[i]` and `headErr[p]` to
 * be the same bytes. The position in `headErr` is not a free dimension: every
 * transition keeps `p = i - j + q`, so the state is `(i, j, q)` and the search
 * is `|baseOut| × |headOut| × (|baseErr| + 1)`.
 */
export function crossing(
  baseOut: readonly string[],
  headOut: readonly string[],
  baseErr: readonly string[],
  headErr: readonly string[],
): Crossed | undefined {
  const [ni, nj, nq] = [baseOut.length, headOut.length, baseErr.length];
  if ((ni + 1) * (nj + 1) * (nq + 1) > SEARCH_LIMIT) return undefined;
  // Nothing to declare if the lengths cannot be a move: exactly as many lines
  // must leave stdout as arrive on stderr, and at least one must.
  if (ni - nj !== headErr.length - nq || ni <= nj) return undefined;

  const key = (i: number, j: number, q: number): number => (i * (nj + 1) + j) * (nq + 1) + q;
  const failed = new Set<number>();

  /**
   * The three moves, as indices into the branches of {@link advance}.
   *
   * 0 — this base stdout line stays on stdout. 1 — this head stderr line was
   * already on base's stderr. 2 — this line crosses, which is only possible
   * when the two sides hold the same bytes at the two positions.
   */
  const options = (i: number, j: number, q: number): number[] => {
    const p = i - j + q;
    const found: number[] = [];
    if (i < ni && j < nj && baseOut[i] === headOut[j]) found.push(0);
    if (q < nq && p < headErr.length && headErr[p] === baseErr[q]) found.push(1);
    if (i < ni && p < headErr.length && baseOut[i] === headErr[p]) found.push(2);
    return found;
  };

  /** Where one move lands. `p` is never carried: it is always `i - j + q`. */
  const advance = (at: readonly [number, number, number], which: number): [number, number, number] => {
    const [i, j, q] = at;
    if (which === 0) return [i + 1, j + 1, q];
    if (which === 1) return [i, j, q + 1];
    return [i + 1, j, q];
  };

  const solve = (i: number, j: number, q: number): boolean => {
    if (i === ni && j === nj && q === nq) return true;
    const id = key(i, j, q);
    if (failed.has(id)) return false;
    for (const which of options(i, j, q)) {
      const [a, b, c] = advance([i, j, q], which);
      if (solve(a, b, c)) return true;
    }
    failed.add(id);
    return false;
  };

  if (!solve(0, 0, 0)) return undefined;

  const fromStdout: number[] = [];
  const ontoStderr: number[] = [];
  let at: [number, number, number] = [0, 0, 0];
  while (at[0] !== ni || at[1] !== nj || at[2] !== nq) {
    const [i, j, q] = at;
    const which = options(i, j, q).find((one) => {
      const [a, b, c] = advance([i, j, q], one);
      return solve(a, b, c);
    });
    if (which === undefined) return undefined;
    if (which === 2) {
      fromStdout.push(i);
      ontoStderr.push(i - j + q);
    }
    at = advance([i, j, q], which);
  }
  return fromStdout.length === 0 ? undefined : { fromStdout, ontoStderr };
}

/**
 * Take a declared **stream crossing** out of both sides, before anything else.
 *
 * The rule names a case and a step and nothing more; everything it claims is
 * decided by {@link crossing} against the two recordings. If no consistent
 * assignment exists — because a line was added, or edited on its way across, or
 * because the move went the other way — this strips nothing, and the case is
 * judged by the ordinary positional comparison and goes red.
 *
 * One-directional for free: run the harness the other way round and stdout
 * *gains* while stderr *loses*, so `headOut` is not a subsequence of `baseOut`
 * and there is no assignment to find. The control for that is in
 * `test/scripts/cli-parity.test.ts` rather than described here.
 */
export function stripCrossings(
  file: string,
  base: readonly string[],
  head: readonly string[],
): {
  readonly base: string[];
  readonly head: string[];
  readonly crossed: { readonly text: string; readonly by: Declared }[];
} {
  const live = DECLARED.filter((rule) => rule.kind === "crossed" && rule.file === file);
  if (live.length === 0) return { base: [...base], head: [...head], crossed: [] };

  const baseSteps = stepStreams(base);
  const headSteps = stepStreams(head);
  const dropBase = new Set<number>();
  const dropHead = new Set<number>();
  const crossed: { text: string; by: Declared }[] = [];

  for (const rule of live) {
    if (rule.kind !== "crossed") continue;
    const here = baseSteps.get(rule.step);
    const there = headSteps.get(rule.step);
    if (here === undefined || there === undefined) continue;

    const baseOut = base.slice(here.stdout[0], here.stdout[1]);
    const headOut = head.slice(there.stdout[0], there.stdout[1]);
    const baseErr = base.slice(here.stderr[0], here.stderr[1]);
    const headErr = head.slice(there.stderr[0], there.stderr[1]);

    const moved = crossing(baseOut, headOut, baseErr, headErr);
    if (moved === undefined) continue;

    for (const at of moved.fromStdout) dropBase.add(here.stdout[0] + at);
    for (const at of moved.ontoStderr) dropHead.add(there.stderr[0] + at);
    crossed.push({ text: moved.fromStdout.map((at) => baseOut[at]!).join("\n"), by: rule });
  }

  return {
    base: base.filter((_, at) => !dropBase.has(at)),
    head: head.filter((_, at) => !dropHead.has(at)),
    crossed,
  };
}

/**
 * Take the declared insertions out of the head side, before anything is aligned.
 *
 * A rule only fires when its pattern matches **no line on the base side of this
 * case**. That is the whole safety property: a rule written for a line that is
 * new cannot be used to hide an edit to a line that was already there, because
 * the moment the base has such a line the rule stops applying and the ordinary
 * positional comparison takes over.
 */
export function stripInsertions(
  base: readonly string[],
  head: readonly string[],
): { readonly head: string[]; readonly inserted: { readonly text: string; readonly by: Declared }[] } {
  const live = DECLARED.filter(
    (rule) => rule.kind === "inserted" && !base.some((line) => rule.pattern.test(line)),
  );
  if (live.length === 0) return { head: [...head], inserted: [] };

  const kept: string[] = [];
  const inserted: { text: string; by: Declared }[] = [];

  for (let at = 0; at < head.length; at++) {
    const line = head[at]!;
    const by = live.find((rule) => rule.kind === "inserted" && rule.pattern.test(line));
    if (by === undefined || by.kind !== "inserted") {
      kept.push(line);
      continue;
    }
    if (by.until === undefined) {
      inserted.push({ text: line, by });
      continue;
    }

    const end = head.findIndex((later, index) => index > at && by.until!.test(later));
    if (end === -1) {
      // The rule names an end that is not there. Strip nothing: a declaration
      // that has stopped describing the output must not quietly eat the rest of
      // the file, and a red case is how somebody finds out.
      kept.push(line);
      continue;
    }
    inserted.push({ text: head.slice(at, end + 1).join("\n"), by });
    at = end;
  }

  return { head: kept, inserted };
}

/**
 * Take the declared removals out of the **base** side, before anything is
 * aligned.
 *
 * The one direction is the whole point. A rule here can only ever make the base
 * side shorter, so it cannot absorb a line the head *gained*: run this harness
 * the other way round — a base from after the change, a head from before it —
 * and the anchor is not there to fire on, the extra head line shifts everything
 * behind it, and the case goes red. That is the property a symmetric pair of
 * `replaced` rules would have thrown away, and it is asserted rather than
 * asserted-about in `test/scripts/cli-parity.test.ts`.
 *
 * A rule with an empty `followedBy` strips **nothing**: a pattern with no
 * anchor is how a rule about one blank line becomes a rule about every blank
 * line, and a declaration that wide is indistinguishable from a normaliser.
 */
export function stripRemovals(base: readonly string[]): {
  readonly base: string[];
  readonly removed: { readonly text: string; readonly by: Declared }[];
} {
  const live = DECLARED.filter((rule) => rule.kind === "removed" && rule.followedBy.length > 0);
  if (live.length === 0) return { base: [...base], removed: [] };

  const kept: string[] = [];
  const removed: { text: string; by: Declared }[] = [];

  for (let at = 0; at < base.length; at++) {
    const line = base[at]!;
    const by = live.find(
      (rule) =>
        rule.kind === "removed" &&
        rule.pattern.test(line) &&
        rule.followedBy.every((after, index) => after.test(base[at + 1 + index] ?? "\u0000")),
    );
    if (by === undefined) kept.push(line);
    else removed.push({ text: line, by });
  }

  return { base: kept, removed };
}

/** Split a case's differences into the declared ones and the rest. */
export function classify(diffs: readonly Difference[]): {
  readonly declared: { readonly diff: Difference; readonly by: Declared }[];
  readonly undeclared: readonly Difference[];
} {
  const declared: { diff: Difference; by: Declared }[] = [];
  const undeclared: Difference[] = [];

  for (const diff of diffs) {
    const by = DECLARED.find((rule) => {
      if (rule.kind === "replaced") return rule.base.test(diff.base) && rule.head.test(diff.head);
      // All four of these are settled before the alignment — three on whole
      // lines rather than on pairs, and `added` on a whole case — so there is
      // nothing here for them to judge.
      if (
        rule.kind === "inserted" ||
        rule.kind === "removed" ||
        rule.kind === "crossed" ||
        rule.kind === "added"
      ) {
        return false;
      }
      const a = rule.pattern.exec(diff.base);
      const b = rule.pattern.exec(diff.head);
      if (a === null || b === null) return false;
      // Same line, same everything, except the number the rule captured. Index
      // 0 is the whole match, which necessarily differs; index 2 is the number.
      return a.length === b.length && a.every((part, index) => index === 0 || index === 2 || part === b[index]);
    });
    if (by === undefined) undeclared.push(diff);
    else declared.push({ diff, by });
  }

  return { declared, undeclared };
}

/**
 * One case, compared: declared insertions removed, then aligned line by line.
 *
 * Pure, and exported for the reason the rest of the judging is: the control
 * that matters here — *an insertion nobody declared still goes red* — is a
 * claim about this function, and a control that cannot be run is a note.
 */
/**
 * Is this whole case a command the base revision does not have?
 *
 * Returns the rule and what it checked, or `undefined` — and the check is the
 * point. A declaration that a case is new would otherwise be a way to silence
 * any case at all, so the rule has to *earn* its exemption on every run: every
 * step of the base recording must have ended in `unknown command "<word>"`, and
 * the two counts are compared. A base that grew the command answers differently
 * on at least one step, the counts stop matching, and the case is judged line
 * by line — which is what a *changed* command deserves and what this kind must
 * never be able to hide.
 *
 * Pure and exported, like the other three strippers, because the control for it
 * is a claim about this function.
 */
export function addedCase(
  file: string,
  base: string,
): { readonly by: Declared; readonly steps: number; readonly refusals: number } | undefined {
  const rule = DECLARED.find((entry) => entry.kind === "added" && entry.file === file);
  if (rule === undefined || rule.kind !== "added") return undefined;

  // `## step N — om-agi <argv>`: the number, then the command line it ran. The
  // pattern stops at the number rather than reading the argv, so a case whose
  // steps are re-worded still counts, and a case whose steps are *renumbered*
  // still counts too.
  const steps = (base.match(/^## step \d+\b/gm) ?? []).length;
  // A recording with no steps in it proves nothing, and would make this rule
  // vacuously true over an empty file — the failure `PARITY-UNDECIDED` exists
  // for, arriving through a different door.
  if (steps === 0) return undefined;

  const word = rule.command.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const refusals = (base.match(new RegExp(`unknown command "${word}"`, "g")) ?? []).length;
  return refusals === steps ? { by: rule, steps, refusals } : undefined;
}

export function diffCase(
  file: string,
  base: string,
  head: string,
): {
  readonly diffs: readonly Difference[];
  readonly inserted: readonly Insertion[];
  readonly removed: readonly Removal[];
  readonly crossed: readonly Crossing[];
  readonly lengths: string | null;
} {
  if (base === head) return { diffs: [], inserted: [], removed: [], crossed: [], lengths: null };

  // Crossings first: they are the only kind that reads the recording's *shape*
  // — which step, which stream — and both of the others work on flat lines.
  const moved = stripCrossings(file, base.split("\n"), head.split("\n"));
  const withdrawn = stripRemovals(moved.base);
  const a = withdrawn.base;
  const stripped = stripInsertions(a, moved.head);
  const b = stripped.head;

  const diffs: Difference[] = [];
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) diffs.push({ file, line: i + 1, base: a[i] ?? "<absent>", head: b[i] ?? "<absent>" });
  }

  const declared = stripped.inserted.length + withdrawn.removed.length + moved.crossed.length;
  return {
    diffs,
    inserted: stripped.inserted.map((entry) => ({ file, text: entry.text, by: entry.by })),
    removed: withdrawn.removed.map((entry) => ({ file, text: entry.text, by: entry.by })),
    crossed: moved.crossed.map((entry) => ({ file, text: entry.text, by: entry.by })),
    lengths:
      a.length === b.length
        ? null
        : `${file}: ${a.length} lines on base, ${b.length} on head` +
          (declared === 0 ? "" : ` (after ${declared} declared insertion(s)/removal(s)/crossing(s))`),
  };
}

async function compare(): Promise<number> {
  const all: Difference[] = [];
  const inserted: Insertion[] = [];
  const removed: Removal[] = [];
  const crossed: Crossing[] = [];
  const missing: string[] = [];
  const cases = selected();

  const added: { name: string; by: Declared; steps: number; headLines: number }[] = [];

  for (const scenario of cases) {
    const name = `${scenario.id}.txt`;
    const base = await Bun.file(join(OUT, "base", name)).text();
    const head = await Bun.file(join(OUT, "head", name)).text();

    // A case whose command the base does not have has no counterpart to be
    // compared against. Checked rather than taken on the declaration's word —
    // see `addedCase` — and reported rather than skipped silently.
    const isNew = addedCase(name, base);
    if (isNew !== undefined) {
      added.push({ name, by: isNew.by, steps: isNew.steps, headLines: head.split("\n").length });
      continue;
    }

    const compared = diffCase(name, base, head);
    all.push(...compared.diffs);
    inserted.push(...compared.inserted);
    removed.push(...compared.removed);
    crossed.push(...compared.crossed);
    if (compared.lengths !== null) missing.push(compared.lengths);
  }

  const { declared, undeclared } = classify(all);

  if (added.length > 0) {
    console.log(`\n${added.length} declared addition(s) — a case with nothing on the other side:\n`);
    for (const entry of added) {
      console.log(`  ${entry.by.id} [added] — ${entry.name}`);
      console.log(`    ${entry.by.reason}`);
      console.log(
        `    checked: all ${entry.steps} step(s) on base answered \`unknown command\`; ` +
          `head produced ${entry.headLines} line(s), which are not compared to anything.`,
      );
      console.log();
    }
  }

  if (declared.length > 0 || inserted.length > 0 || removed.length > 0 || crossed.length > 0) {
    console.log(
      `\n${declared.length} declared difference(s), ${inserted.length} declared insertion(s), ` +
        `${removed.length} declared removal(s) and ${crossed.length} declared crossing(s) — ` +
        `printed, not hidden:\n`,
    );
    for (const rule of DECLARED) {
      const mine = declared.filter((d) => d.by === rule);
      const mineInserted = inserted.filter((entry) => entry.by === rule);
      const mineRemoved = removed.filter((entry) => entry.by === rule);
      const mineCrossed = crossed.filter((entry) => entry.by === rule);
      if (
        mine.length === 0 &&
        mineInserted.length === 0 &&
        mineRemoved.length === 0 &&
        mineCrossed.length === 0
      ) {
        continue;
      }
      console.log(
        `  ${rule.id} [${rule.kind}] — ${mine.length} changed line(s), ` +
          `${mineInserted.length} inserted line(s), ${mineRemoved.length} removed line(s), ` +
          `${mineCrossed.length} crossing(s)`,
      );
      console.log(`    ${rule.reason}`);
      for (const { diff } of mine) {
        console.log(`    ${diff.file}:${diff.line}`);
        console.log(`      base: ${diff.base.trim()}`);
        console.log(`      head: ${diff.head.trim()}`);
      }
      for (const entry of mineInserted) {
        console.log(`    ${entry.file}`);
        console.log(`      head only: ${entry.text.trim()}`);
      }
      for (const entry of mineRemoved) {
        console.log(`    ${entry.file}`);
        console.log(`      base only: ${JSON.stringify(entry.text)}`);
      }
      for (const entry of mineCrossed) {
        const block = entry.text.split("\n");
        console.log(`    ${entry.file} — ${block.length} line(s) off stdout, onto stderr, unchanged:`);
        // Whole, because the claim is about every byte of it. A harness that
        // declared a 250-line move and printed three lines of it would be
        // asking to be believed.
        for (const line of block) console.log(`      ${line}`);
      }
      console.log();
    }
  }

  if (undeclared.length === 0 && missing.length === 0) {
    console.log(
      `\nPARITY-OK — ${cases.length} case(s)${ONLY === undefined ? "" : ` of ${SCENARIOS.length}`}, ` +
        `${cases.reduce((n, s) => n + s.steps.length, 0)} invocation(s), ` +
        `no undeclared difference in stdout, stderr, exit code or the sandbox tree.`,
    );
    return 0;
  }

  for (const note of missing) console.error(`\nlength differs — ${note}`);
  console.error(`\n${undeclared.length} undeclared difference(s):\n`);
  for (const diff of undeclared.slice(0, 200)) {
    console.error(`  ${diff.file}:${diff.line}`);
    console.error(`    base: ${diff.base}`);
    console.error(`    head: ${diff.head}`);
  }
  if (undeclared.length > 200) console.error(`  … and ${undeclared.length - 200} more`);
  console.error(`\nRecordings: ${join(OUT, "base")} and ${join(OUT, "head")}`);
  return 1;
}

