#!/usr/bin/env bun
/**
 * Two revisions of this CLI, run side by side, compared byte for byte.
 *
 * ## Why it exists
 *
 * `bin/om-agi.ts` was one 3364-line file that almost every task had to open, so
 * two tasks in parallel edited the same file and merged by hand. Splitting it
 * per command fixes that — but a refactor whose whole claim is "nothing
 * changed" needs the claim *measured*, not asserted in a commit message. The
 * suite cannot do it: it checks what someone thought to check, and the failure
 * mode of a move is the byte nobody thought about.
 *
 * So this runs every command, every alias, every subcommand and the error path
 * of each, on **both** revisions, and diffs everything that came out: stdout,
 * stderr, exit code, and the tree each run wrote into its sandbox.
 *
 * ## The four things that make the comparison mean something
 *
 * 1. **Pinned to a commit, not to a file in this repo.** The `--base` side is
 *    materialised with `git archive`, so nobody has to trust a golden file that
 *    was generated by the same change it is supposed to be checking.
 * 2. **Both sides land at the same absolute path.** The engine is always at
 *    {@link ENGINE}, and case N's sandbox is always at `runs/N`, whichever side
 *    is running. Paths are then identical by construction rather than by a
 *    normaliser, and a normaliser is exactly where a real difference hides.
 * 3. **Four normalisers, and they are counted.** A clock, a UUID, a duration
 *    and a `mkdtemp` suffix are genuinely per-run. Every substitution is
 *    counted per case and the counts are written into the recording, so a side
 *    that replaced a different *number* of things fails the diff even when the
 *    replacements made the text match.
 * 4. **The controls run before the result is believed.** `--selftest` runs the
 *    base against itself (must be empty) and against a one-character mutation
 *    of an error message (must be red). A harness nobody proved can see a
 *    change is a harness that reports "no change" for free.
 *
 * ## The third answer, and why a proof tool needs one
 *
 * `PARITY-OK` and a list of differences are answers about two engines. Neither
 * of them is the right answer to *"this comparison did not happen"* — and that
 * state was reachable, quietly: point both sides at an empty directory and
 * every invocation on both sides fails identically with the same ENOENT, which
 * is parity by this harness's own definition and an `OK` earned by neither side
 * working (odd2, row `D-P6`). It is the same family as the bug `gate4` found,
 * where the harness could not see a deleted file.
 *
 * So there is a third answer: **`PARITY-UNDECIDED`, exit 3** — a refusal to
 * judge, not a verdict. It is raised by {@link ParityUndecided} from three
 * places, each of which is a thing that must be true *before* a comparison means
 * anything:
 *
 * 1. `bun` and `git` are on this PATH. There used to be a `?? "bun"` fallback
 *    here, which made both sides fail with the same ENOENT and report parity.
 * 2. Each side really has a `bin/om-agi.ts`, **and running it exits 0** — the
 *    liveness check. Checking only that the file exists would close the probe
 *    and leave the hole: two sides whose engine is present and broken in the
 *    same way still compare equal. Only the exit code is read, never the text,
 *    so this cannot become the golden file the header refuses.
 * 3. Two *different* specs that resolve to byte-identical trees. That is
 *    `--base HEAD --head .` on a clean checkout: two names, one tree, nothing to
 *    judge. Two identical specs are not refused, because running one revision
 *    against itself is what control 1 does on purpose.
 *
 * ## What it deliberately cannot reach
 *
 * `observe enable` and `observe audit` require a terminal and have no `--yes`.
 * A harness driving the CLI through a pipe can therefore never turn capture on,
 * and only their refusal paths are recorded. That is a property of the commands,
 * not a gap in the matrix.
 *
 * The liveness check above narrows the free pass; it does not close it. Two
 * engines that both run, where one scenario fails identically on both sides
 * because of something in the environment neither side controls, is still
 * reported as parity — and correctly so, because parity is what was measured.
 * A harness that compares two sides cannot see a fault both sides share. That
 * limit is why `--selftest`'s controls exist and why they run on every
 * `bun test` rather than when somebody remembers.
 *
 * ## Usage
 *
 *     bun run scripts/cli-parity.ts --base <rev|dir> --head <rev|dir>
 *     bun run scripts/cli-parity.ts --base <rev> --head . --structure
 *     bun run scripts/cli-parity.ts --base <rev> --selftest
 *     bun run scripts/cli-parity.ts --base <dir> --selftest --only 02-unknown --work <dir>
 *
 * Exit 0 when every case matches (or matches a declared difference, printed in
 * full on every run), 1 when something differs, 3 when the run refused to judge.
 *
 * ## Why the run is behind `import.meta.main`, and the parts above it exported
 *
 * This file used to be 28 lines of top-level work, which meant a test could not
 * so much as `import` it: the first thing the import did was read `--base` off
 * the test runner's own command line, fail to find it, and `process.exit(2)` —
 * taking the whole suite with it. The harness that proves a refactor changed
 * nothing was therefore the one file in `scripts/` that nothing could check.
 *
 * So the entry point is guarded and the judging parts — {@link normalise},
 * {@link classify}, {@link difference}, {@link isComment} and the
 * {@link SCENARIOS} matrix itself — are exported and pure.
 * `test/scripts/cli-parity.test.ts` asks them the two questions that matter for
 * a proof tool, and neither of them is "did this file get bigger":
 *
 *   1. *Do the two controls still hold?* — answered by really running
 *      `--selftest` over one scenario on every `bun test`, because a control
 *      that is only run by hand is a control that was run once.
 *   2. *Does the matrix still describe this CLI?* — answered statically: every
 *      `case` in `bin/om-agi.ts` has a step here, every fixture the matrix names
 *      is on disk, and control 2's needle is still a string the CLI prints. A
 *      file of exactly the same size goes stale the moment the CLI moves under
 *      it, which is why size is the wrong question to ask of this half of
 *      `scripts/`.
 */

